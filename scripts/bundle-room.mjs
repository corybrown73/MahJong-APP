/**
 * Bundle the room module (and the engine and AI it stands on) into a single
 * dependency-free ES module the Supabase Edge Function can import.
 *
 * The server and the app run byte-identical rules because they run the same
 * source; this script is the only thing between the two.
 */
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));

await build({
  entryPoints: [path.join(root, 'packages/room/src/index.ts')],
  outfile: path.join(root, 'supabase/functions/bahay-room/_room.js'),
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  banner: {
    js: '// Generated by scripts/bundle-room.mjs — do not edit.\n// Source of truth: packages/room, packages/engine, packages/ai.',
  },
});

console.log('bundled supabase/functions/bahay-room/_room.js');
